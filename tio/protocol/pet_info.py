@dataclass(frozen=True)
class PetInfo:
    human_equipment: bool
    fields: dict[str, int | bytes | str]


def _schema(human, fields):
    if type(human) is not bool:
        raise PacketError('Explicit equipment profile required')
    appearance = fields.get('0x6d0203')
    owner = fields.get('0x8c4565')
    if appearance not in (0, 1) or owner not in (0, 1):
        raise PacketError('Expected canonical appearance/owner flags')
    # These branches consume extra fields not covered by the current schemas.
    for key in ('0x8c4c34','0x8c4cb6','0x8c4d38','0x8c4d88'):
        if fields.get(key) == 1:
            raise PacketError('Timed PetInfo state not yet supported: '+key)
    schema = SCHEMAS[(human,bool(appearance),bool(owner))]
    if fields.get('0x8c4f74',0):
        schema += (('0x8c4f9c', 2, 'WideString'),)
    return schema


def encode_pet_info(pet: PetInfo) -> bytes:
    schema = _schema(pet.human_equipment,pet.fields)
    if set(pet.fields) != {field for field,_,_ in schema}:
        raise PacketError('PetInfo field set does not match selected layout')
    w = Writer().u8(0x66)
    for field,size,reader in schema:
        value=pet.fields[field]
        if reader=='WideString':
            from .equipment_templates import wide_name
            w.data.extend(wide_name(value))
        elif reader=='CString':
            if not isinstance(value,bytes) or len(value)>255 or b'\0' in value:
                raise PacketError('Expected bounded CString name')
            w.data.extend(value+b'\0')
        else:
            w.data.extend(uint(value,size*8).to_bytes(size,'little'))
    return w.build()


def decode_pet_info(packet: bytes, *, human_equipment: bool) -> PetInfo:
    if type(human_equipment) is not bool:
        raise PacketError('Explicit equipment profile required')
    r=Reader(packet)
    if r.u8()!=0x66:
        raise PacketError('Expected PetInfo66')
    fields={}
    # Schema is chosen after reading the fixed header and appearance flag.
    initial=SCHEMAS[(human_equipment,False,False)]
    for field,size,reader in initial:
        if reader=='CString':
            name=bytearray()
            while (char:=r.u8())!=0:
                name.append(char)
                if len(name)>255:raise PacketError('PetInfo name too long')
            fields[field]=bytes(name)
        else:
            fields[field]=int.from_bytes(r.read(size),'little')
        if field=='0x6d0203':break
    if fields['0x6d0203'] not in (0,1) or fields['0x8c4565'] not in (0,1):
        raise PacketError('Invalid PetInfo profile flag')
    schema=SCHEMAS[(human_equipment,bool(fields['0x6d0203']),bool(fields['0x8c4565']))]
    for field,size,reader in schema:
        if field not in fields:
            fields[field]=int.from_bytes(r.read(size),'little')
    if fields['0x8c4f74']:
        from .equipment_templates import read_name
        fields['0x8c4f9c'] = read_name(r)
    _schema(human_equipment,fields)
    r.finish()
    return PetInfo(human_equipment,fields)
